//   同一份指纹面枚举脚本，在【本机真 Chrome 150.0.7871.187】和【我们的 sentinel VM】里
//   各跑一次，对 Object.keys(window) 做差集。脚本见 scratchpad/fp_surface.js / key_diff.js。
//   实测：真 Chrome 可枚举自有键 237 个，我们 151 个。
//
// 【为什么盯 Object.keys 而不是 getOwnPropertyNames】
//   两者差 5 倍（真 Chrome 1232 vs 237）—— getOwnPropertyNames 含全部不可枚举的
//   Web API 构造器。sentinel 的 p[11]/p[12] 抽的是 window 的键，补错池子等于白干。
//   ⚠ 这两个口径别混：仓库里曾有「浏览器真实 window 有 223 个自有键」的注释，
//     那说的是可枚举那一栏，和 1232 不是一回事。
//
// 【最要紧的一条】NON_ENUMERABLE 里那批
//   真浏览器里 Array / Math / JSON / Promise / Event / MutationObserver 这些在 window 上
//   都是【不可枚举】的 —— Object.keys(window) 永远不会返回它们。
//   而 vm.createContext({...}) 会把传进去的一切变成【可枚举】自有属性，
//   于是我们铸出来的 p[12] 抽到过 "Promise" —— 那个值在真浏览器里根本不可能出现，
//   单个样本即可判死。
//   ⚠ 不能改成"不往 context 传这些内建"：显式传是为了跨 realm 身份
//     （宿主建的数组要能通过 VM 里的 instanceof Array）。所以照传，只改可枚举性。

